// Приведение текста к «сжатому» виду для поиска стоп-слов — против обходов вида
// «Н.а.р.к.о.т.и.к», «нaркотик» (латинская a), «нааааркотик», «н а р к о т и к».
// Одинаково применяется и к вопросу, и к стоп-словам, поэтому сравнение честное.

/** Латинские буквы и цифры, похожие на кириллицу. */
const LOOKALIKE: Record<string, string> = {
  a: 'а', b: 'в', c: 'с', e: 'е', h: 'н', k: 'к', m: 'м', o: 'о', p: 'р', t: 'т', x: 'х', y: 'у',
  '0': 'о', '3': 'з', '4': 'ч', '6': 'б', '@': 'а',
}

export function compact(text: string): string {
  let out = ''
  for (const raw of text.toLowerCase().replace(/ё/g, 'е')) {
    const ch = LOOKALIKE[raw] ?? raw
    // Оставляем только буквы; пробелы, точки, дефисы и прочее между буквами выбрасываем.
    if (!/\p{L}/u.test(ch)) continue
    // Повторы подряд схлопываем: «нааааркотик» → «наркотик».
    if (out.endsWith(ch)) continue
    out += ch
  }
  return out
}

/** Минимальная длина стоп-слова после сжатия — короче даёт слишком много ложных срабатываний. */
export const MIN_KEYWORD = 3
